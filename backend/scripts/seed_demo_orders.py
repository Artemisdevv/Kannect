"""Create deterministic demo orders and invoices through the API.

Usage (from backend/, after seed_demo.py and seed_demo_suppliers.py):
    python scripts/seed_demo_orders.py          # dry run
    python scripts/seed_demo_orders.py --apply

Stable client IDs make reruns idempotent. Orders are accepted through the supplier API so
invoice numbers and lifecycle state are generated by the same code as normal traffic.
GST is intentionally not calculated and invoices label it as unimplemented.
"""

import argparse
import json
import os
import uuid
from urllib.error import HTTPError
from urllib.request import Request, urlopen

BASE_URL = os.getenv("KANNect_API_URL", "http://localhost:8000").rstrip("/")
OTP = os.getenv("DEMO_OTP", "123456")
PHONE_PREFIX = "+91900000"
SUPPLIERS = [
    (f"{PHONE_PREFIX}0101", "Mary Matha Provision", f"{PHONE_PREFIX}0002"),
    (f"{PHONE_PREFIX}0102", "Nair's Kada", f"{PHONE_PREFIX}0003"),
    (f"{PHONE_PREFIX}0103", "Fathima Supermarket", f"{PHONE_PREFIX}0004"),
]


def api(method: str, path: str, *, token: str | None = None, body: dict | None = None) -> dict:
    headers = {"Content-Type": "application/json"}
    if token:
        headers["Authorization"] = f"Bearer {token}"
    data = json.dumps(body).encode() if body is not None else None
    request = Request(f"{BASE_URL}{path}", data=data, headers=headers, method=method)
    try:
        with urlopen(request, timeout=30) as response:
            payload = response.read()
    except HTTPError as exc:
        detail = exc.read().decode(errors="replace")
        raise RuntimeError(f"{method} {path}: HTTP {exc.code}: {detail}") from exc
    return json.loads(payload) if payload else {}


def login(phone: str, role: str) -> str:
    api("POST", "/api/v1/auth/otp/request", body={"phone": phone})
    result = api(
        "POST", "/api/v1/auth/otp/verify", body={"phone": phone, "role": role, "otp": OTP}
    )
    return result["token"]


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--apply", action="store_true")
    args = parser.parse_args()
    if not args.apply:
        print(
            "Dry run: would seed accepted orders for "
            f"{', '.join(shop for _, shop, _ in SUPPLIERS)} at {BASE_URL}."
        )
        print("Run with --apply to call the API. Stable IDs make it safe to rerun.")
        return

    for supplier_phone, shop_name, phone in SUPPLIERS:
        supplier_token = login(supplier_phone, "supplier")
        supplier = api("GET", "/api/v1/supplier", token=supplier_token)
        supplier_id = supplier["id"]
        listings = api("GET", "/api/v1/supplier/products", token=supplier_token)["items"]
        available = [row for row in listings if row["available"]]
        if not available:
            raise RuntimeError(f"Demo supplier {supplier_phone} has no available products")
        product_id = available[0]["product"]["id"]
        retailer_token = login(phone, "retailer")
        # Deterministic idempotency key: one seeded order per demo shop and supplier.
        client_id = str(uuid.uuid5(uuid.NAMESPACE_URL, f"kannect-demo-order:{phone}:{supplier_id}"))
        order = api(
            "POST",
            "/api/v1/shop/orders",
            token=retailer_token,
            body={
                "client_id": client_id,
                "supplier_id": supplier_id,
                "items": [{"product_id": product_id, "packs": 1}],
                "note": "Seeded demo order",
            },
        )
        if order["status"] == "placed":
            order = api(
                "POST",
                f"/api/v1/supplier/orders/{order['id']}/status",
                token=supplier_token,
                body={"status": "accepted", "note": "Demo order accepted"},
            )
        invoice = api(
            "GET", f"/api/v1/shop/orders/{order['id']}/invoice", token=retailer_token
        )
        print(
            f"{shop_name}: order {order['id']} ({order['status']}), "
            f"invoice {invoice['number']}; GST not implemented"
        )


if __name__ == "__main__":
    main()
